"""Make zh_extra.txt (published) from zh_extra_en.txt (private source with the game's English text).

zh_extra_en.txt: one "English<TAB>Chinese" per line, file escapes \\n and \\\\ (see ZhFallback.cs).
zh_extra.txt:    one "key<TAB>Chinese" per line, key = first 16 hex digits of SHA-1 over the UTF-8 bytes of the
                 unescaped English text (OriCoop.Ui.ZhTextKey.Of). The output holds no game text.

    python src/assets/zh-text/hash-zh-extra.py [--src zh_extra_en.txt] [--out zh_extra.txt]
"""
import argparse
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent


def unescape(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s) and s[i + 1] in "n\\":
            out.append("\n" if s[i + 1] == "n" else "\\")
            i += 2
            continue
        out.append(s[i])
        i += 1
    return "".join(out)


def key(english):
    return hashlib.sha1(english.encode("utf-8")).hexdigest()[:16]


def read_pairs(path):
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        # English entries such as '#Naru#,...' are data; comments start with '# ' (as in check_terms.py).
        if not line or "\t" not in line or line.startswith("# "):
            continue
        source, target = line.split("\t", 1)
        if source and target:
            yield unescape(source), target   # the Chinese side stays escaped, exactly as in the source


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=Path, default=HERE / "zh_extra_en.txt")
    ap.add_argument("--out", type=Path, default=HERE / "zh_extra.txt")
    a = ap.parse_args()
    rows, seen = [], {}
    for english, chinese in read_pairs(a.src):
        k = key(english)
        if k in seen and seen[k] != english:
            raise SystemExit("hash collision: %r / %r" % (seen[k], english))
        seen[k] = english
        rows.append((k, chinese))
    rows.sort()
    head = [
        "# Chinese for game texts whose Chinese entry is blank (read by ZhFallback.cs).",
        "# key<TAB>Chinese; key = first 16 hex digits of SHA-1 over the UTF-8 English text (no game text here).",
        "# Generated by hash-zh-extra.py; edit the private zh_extra_en.txt and regenerate.",
    ]
    a.out.write_text("\n".join(head + ["%s\t%s" % r for r in rows]) + "\n", encoding="utf-8", newline="\n")
    print("zh_extra: %d entries -> %s" % (len(rows), a.out))


if __name__ == "__main__":
    main()
